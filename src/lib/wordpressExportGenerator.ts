import { BLOG_POSTS } from '../data/blogData';

export function generateWordPressWxrXml(domain: string = 'https://dakterachen.com'): string {
  const cleanDomain = domain.replace(/\/+$/, '');
  const now = new Date().toUTCString();

  const itemsXml = BLOG_POSTS.map((post, idx) => {
    const postId = 1000 + idx;
    const postDate = post.publishedDate && post.publishedDate.includes('-')
      ? `${post.publishedDate} 10:00:00`
      : '2026-10-29 10:00:00';

    // Construct full rich HTML content
    const sectionsHtml = post.contentSections
      .map((sec) => {
        const paragraphs = sec.paragraphsBn.map((p) => `<p>${p}</p>`).join('\n');
        const tips = sec.tipsListBn && sec.tipsListBn.length > 0
          ? `<ul>${sec.tipsListBn.map((t) => `<li>${t}</li>`).join('')}</ul>`
          : '';
        const warning = sec.warningCalloutBn
          ? `<blockquote style="background:#fef2f2; border-left:4px solid #ef4444; padding:12px; margin:16px 0;"><strong>সতর্কতা:</strong> ${sec.warningCalloutBn}</blockquote>`
          : '';
        return `<h3>${sec.titleBn}</h3>\n${paragraphs}\n${tips}\n${warning}`;
      })
      .join('\n\n');

    const takeawaysHtml = post.keyTakeawaysBn && post.keyTakeawaysBn.length > 0
      ? `<div style="background:#f0fdf4; border:1px solid #bbf7d0; border-radius:8px; padding:16px; margin-bottom:20px;">
          <h4 style="color:#166534; margin-top:0;">মূল জরুরি বিষয়সমূহ:</h4>
          <ul>${post.keyTakeawaysBn.map((k) => `<li>${k}</li>`).join('')}</ul>
        </div>`
      : '';

    const authorHtml = `<p style="font-size:12px; color:#64748b; margin-top:30px; border-top:1px solid #e2e8f0; padding-top:12px;">
      লেখক: <strong>${post.author.nameBn}</strong> (${post.author.roleBn}) |
      চিকিৎসা পর্যালোচক: <strong>${post.reviewedBy.nameBn}</strong> (${post.reviewedBy.degreesBn})
    </p>`;

    const fullContent = `${takeawaysHtml}\n${sectionsHtml}\n${authorHtml}`;

    return `  <item>
    <title><![CDATA[${post.titleBn}]]></title>
    <link>${cleanDomain}/blog/${post.slug}</link>
    <pubDate>${new Date(postDate).toUTCString()}</pubDate>
    <dc:creator><![CDATA[${post.author.nameBn}]]></dc:creator>
    <guid isPermaLink="false">${cleanDomain}/?p=${postId}</guid>
    <description><![CDATA[${post.excerptBn}]]></description>
    <content:encoded><![CDATA[${fullContent}]]></content:encoded>
    <excerpt:encoded><![CDATA[${post.excerptBn}]]></excerpt:encoded>
    <wp:post_id>${postId}</wp:post_id>
    <wp:post_date><![CDATA[${postDate}]]></wp:post_date>
    <wp:post_date_gmt><![CDATA[${postDate}]]></wp:post_date_gmt>
    <wp:comment_status><![CDATA[open]]></wp:comment_status>
    <wp:ping_status><![CDATA[closed]]></wp:ping_status>
    <wp:post_name><![CDATA[${post.slug}]]></wp:post_name>
    <wp:status><![CDATA[publish]]></wp:status>
    <wp:post_parent>0</wp:post_parent>
    <wp:menu_order>0</wp:menu_order>
    <wp:post_type><![CDATA[post]]></wp:post_type>
    <wp:post_password><![CDATA[]]></wp:post_password>
    <wp:is_sticky>0</wp:is_sticky>
    <category domain="category" nicename="${post.categoryKey}"><![CDATA[${post.categoryBn}]]></category>
    ${post.tags.map((t) => `<category domain="post_tag" nicename="${encodeURIComponent(t)}"><![CDATA[${t}]]></category>`).join('\n    ')}
  </item>`;
  }).join('\n');

  return `<?xml version="1.0" encoding="UTF-8" ?>
<!-- This is a WordPress eXtended RSS file generated by Dakter Achen Platform -->
<!-- It contains all 106+ Medical Blog Posts ready to import into WordPress via Tools > Import > WordPress -->
<rss version="2.0"
	xmlns:excerpt="http://wordpress.org/export/1.2/excerpt/"
	xmlns:content="http://purl.org/rss/1.0/modules/content/"
	xmlns:wfw="http://wellformedweb.org/CommentAPI/"
	xmlns:dc="http://purl.org/dc/elements/1.1/"
	xmlns:wp="http://wordpress.org/export/1.2/"
>
<channel>
	<title>Dakter Achen</title>
	<link>${cleanDomain}</link>
	<description>Health Decision Platform - 106+ Medical Articles</description>
	<pubDate>${now}</pubDate>
	<language>bn</language>
	<wp:wxr_version>1.2</wp:wxr_version>
	<wp:base_site_url>${cleanDomain}</wp:base_site_url>
	<wp:base_blog_url>${cleanDomain}</wp:base_blog_url>

	<wp:category>
		<wp:term_id>101</wp:term_id>
		<wp:category_nicename>preventive</wp:category_nicename>
		<wp:category_parent></wp:category_parent>
		<wp:cat_name><![CDATA[রোগ প্রতিরোধ ও ভ্যাকসিন]]></wp:cat_name>
	</wp:category>
	<wp:category>
		<wp:term_id>102</wp:term_id>
		<wp:category_nicename>chronic</wp:category_nicename>
		<wp:category_parent></wp:category_parent>
		<wp:cat_name><![CDATA[দীর্ঘস্থায়ী রোগ ও ডায়াবেটিস]]></wp:cat_name>
	</wp:category>
	<wp:category>
		<wp:term_id>103</wp:term_id>
		<wp:category_nicename>maternal_child</wp:category_nicename>
		<wp:category_parent></wp:category_parent>
		<wp:cat_name><![CDATA[মা ও শিশু স্বাস্থ্য]]></wp:cat_name>
	</wp:category>
	<wp:category>
		<wp:term_id>104</wp:term_id>
		<wp:category_nicename>emergency</wp:category_nicename>
		<wp:category_parent></wp:category_parent>
		<wp:cat_name><![CDATA[জরুরি প্রাথমিক চিকিৎসা]]></wp:cat_name>
	</wp:category>
	<wp:category>
		<wp:term_id>105</wp:term_id>
		<wp:category_nicename>lifestyle</wp:category_nicename>
		<wp:category_parent></wp:category_parent>
		<wp:cat_name><![CDATA[জীবনযাপন ও পুষ্টি]]></wp:cat_name>
	</wp:category>
	<wp:category>
		<wp:term_id>106</wp:term_id>
		<wp:category_nicename>mental</wp:category_nicename>
		<wp:category_parent></wp:category_parent>
		<wp:cat_name><![CDATA[মানসিক স্বাস্থ্য ও ঘুম]]></wp:cat_name>
	</wp:category>

${itemsXml}
</channel>
</rss>`;
}
